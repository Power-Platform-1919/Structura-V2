/* The task list: todo.json (the source of truth) and docs/TODO.md (the readable copy, always made from todo.json).

   node tools/todo.mjs list [id]             progress of every task (or one task with all its subtasks)
   node tools/todo.mjs set <id> <status> [note]   status: done | in_progress | todo | blocked
                                             A step marked done MUST come with a note: a short description of what was done and
                                             changed (files, pull request, numbers), so the list reads as a history. The date is
                                             added automatically. `check` fails when a done step has no note.
   node tools/todo.mjs render                rewrite docs/TODO.md from todo.json
   node tools/todo.mjs check                 fail when todo.json is inconsistent or docs/TODO.md is out of date

   A task that has subtasks never gets a status by hand: it is worked out from its subtasks (all done is done, some done or
   in progress is in_progress, all blocked is blocked, otherwise todo). A decision waiting inside a task is shown in the
   "waiting on a decision" column, not by blocking the whole task. Set the subtask, and the task follows.
   The unit test tests/unit/todo.test.js runs "check", so the list and the readable copy cannot drift apart. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const JSON_FILE = join(root, 'todo.json');
const MARKDOWN_FILE = join(root, 'docs', 'TODO.md');
export const STATUSES = ['done', 'in_progress', 'todo', 'blocked'];
const FIRST_TRACKED = 15;        // tasks 1 to 14 were finished before this list was made granular: they are summarized, not listed

/** The status of an item: its own when it has no subtasks, otherwise worked out from them. Writes it back into the item. */
export function derive(item) {
  const children = item.subtasks || [];
  if (!children.length) return item.status;
  const states = children.map(derive);
  let status;
  if (states.every((s) => s === 'done')) status = 'done';
  else if (states.some((s) => s === 'in_progress' || s === 'done')) status = 'in_progress';
  else if (states.every((s) => s === 'blocked')) status = 'blocked';   // everything left is waiting
  else status = 'todo';
  item.status = status;
  return status;
}

export function leaves(item) {
  const children = item.subtasks || [];
  return children.length ? children.flatMap(leaves) : [item];
}

export function find(tasks, id) {
  const walk = (list) => { for (const item of list) { if (item.id === id) return item; const hit = walk(item.subtasks || []); if (hit) return hit; } return null; };
  return walk(tasks);
}

export function load() { return JSON.parse(readFileSync(JSON_FILE, 'utf8')); }
export function save(todo) { writeFileSync(JSON_FILE, JSON.stringify(todo, null, 2) + '\n'); }

const MARK = { done: '[x]', in_progress: '[~]', todo: '[ ]', blocked: '[!]' };

function renderItem(item, depth) {
  const note = item.note ? ` *(${item.note}${item.doneOn ? `; done ${item.doneOn}` : ''})*` : '';
  let out = `${'  '.repeat(depth)}- ${MARK[item.status]} **${item.id}** ${item.title}${note}\n`;
  for (const child of item.subtasks || []) out += renderItem(child, depth + 1);
  return out;
}

export function renderMarkdown(todo) {
  for (const task of todo.tasks) derive(task);
  const tracked = todo.tasks.filter((task) => Number(task.id) >= FIRST_TRACKED);
  const earlier = todo.tasks.filter((task) => Number(task.id) < FIRST_TRACKED);
  const count = (list) => { const all = list.flatMap(leaves); return { done: all.filter((x) => x.status === 'done').length, total: all.length, blocked: all.filter((x) => x.status === 'blocked').length, working: all.filter((x) => x.status === 'in_progress').length }; };
  const all = count(tracked);
  let out = `# Task list\n\nMade from \`todo.json\` by \`node tools/todo.mjs render\`. Do not edit this file by hand: change a status with \`node tools/todo.mjs set <id> <status>\` and the task, its parents and this file follow.\n\n`;
  out += `Legend: [x] done, [~] in progress, [ ] to do, [!] blocked (waiting for a decision from you or for another task).\n\n`;
  out += `**Overall (tasks ${FIRST_TRACKED} and up): ${all.done} of ${all.total} steps done, ${all.blocked} waiting on a decision, ${all.total - all.done - all.blocked} still to do.**\n\n`;
  out += `| Task | Status | Done | Waiting on a decision |\n|---|---|---|---|\n`;
  for (const task of tracked) { const c = count([task]); out += `| ${task.id}. ${task.title} | ${task.status} | ${c.done} of ${c.total} | ${c.blocked} |\n`; }
  const e = count(earlier);
  out += `| 1 to ${FIRST_TRACKED - 1}. Earlier work (V2 boot, Power Platform, redesign, overview, icons, audits): ${earlier.length} tasks | done | ${e.done} of ${e.total} | 0 |\n\n`;
  out += `Companion documents: [feature-technology-map.md](feature-technology-map.md) (what each part is built with and the plan), [mature-libraries-plan.md](mature-libraries-plan.md), [deep-dive-analysis-2026-10.md](deep-dive-analysis-2026-10.md).\n\n`;
  for (const task of tracked) {
    const c = count([task]);
    out += `## ${task.id}. ${task.title}\n\n*${task.status}, ${c.done} of ${c.total} steps done*${task.brief ? '. ' + task.brief : ''}\n\n`;
    for (const sub of task.subtasks || []) out += renderItem(sub, 0);
    out += '\n';
  }
  return out;
}

/** Problems with the list itself; an empty list means it is sound */
export function problems(todo) {
  const found = [];
  const seen = new Set();
  const walk = (item, isTracked) => {
    if (seen.has(item.id)) found.push(`duplicate id ${item.id}`);
    seen.add(item.id);
    if (!STATUSES.includes(item.status)) found.push(`${item.id} has the status "${item.status}"`);
    if (!item.title) found.push(`${item.id} has no title`);
    if (item.status === 'done' && !(item.subtasks || []).length && !item.note) found.push(`${item.id} is done but has no note saying what was done (node tools/todo.mjs set ${item.id} done "what changed")`);
    const children = item.subtasks || [];
    if (children.length) {
      const stored = item.status;
      const copy = JSON.parse(JSON.stringify(item));
      if (isTracked && derive(copy) !== stored) found.push(`${item.id} says "${stored}" but its subtasks make it "${copy.status}" (run: node tools/todo.mjs render)`);
    }
    for (const child of children) walk(child, isTracked);
  };
  for (const task of todo.tasks) walk(task, Number(task.id) >= FIRST_TRACKED);
  return found;
}

function main() {
  const [command, ...args] = process.argv.slice(2);
  const todo = load();
  if (command === 'list') {
    for (const task of todo.tasks) derive(task);
    if (args[0]) {
      const item = find(todo.tasks, args[0]);
      if (!item) { console.error('no task ' + args[0]); process.exit(1); }
      process.stdout.write(renderItem(item, 0));
      return;
    }
    for (const task of todo.tasks.filter((x) => Number(x.id) >= FIRST_TRACKED)) { const all = leaves(task); console.log(`${task.id.padEnd(3)} ${task.status.padEnd(12)} ${String(all.filter((x) => x.status === 'done').length).padStart(3)}/${String(all.length).padEnd(3)} ${task.title}`); }
  } else if (command === 'set') {
    const [id, status, ...note] = args;
    const item = find(todo.tasks, id);
    if (!item) { console.error('no task ' + id); process.exit(1); }
    if (!STATUSES.includes(status)) { console.error('status must be one of ' + STATUSES.join(', ')); process.exit(1); }
    if ((item.subtasks || []).length) { console.error(`${id} has subtasks: set one of them, the task follows`); process.exit(1); }
    const wasDone = item.status === 'done';
    item.status = status;
    if (status === 'done' && !note.length && !item.note) { console.error(`${id}: say what was done, as a short note: node tools/todo.mjs set ${id} done "what changed"`); process.exit(1); }
    if (note.length) item.note = note.join(' ');
    if (status === 'done') { if (!wasDone || note.length || !item.doneOn) item.doneOn = new Date().toISOString().slice(0, 10); } else delete item.doneOn;
    for (const task of todo.tasks) derive(task);
    save(todo);
    writeFileSync(MARKDOWN_FILE, renderMarkdown(todo));
    console.log(`${id} is now ${status}`);
  } else if (command === 'render') {
    for (const task of todo.tasks) derive(task);
    save(todo);
    writeFileSync(MARKDOWN_FILE, renderMarkdown(todo));
    console.log('docs/TODO.md written');
  } else if (command === 'check') {
    const found = problems(todo);
    let current = '';
    try { current = readFileSync(MARKDOWN_FILE, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
    if (current !== renderMarkdown(JSON.parse(JSON.stringify(todo)))) found.push('docs/TODO.md is out of date (run: node tools/todo.mjs render)');
    if (found.length) { console.error(found.join('\n')); process.exit(1); }
    console.log('todo.json and docs/TODO.md are consistent');
  } else {
    console.log('usage: node tools/todo.mjs list [id] | set <id> <status> [note] | render | check');
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
